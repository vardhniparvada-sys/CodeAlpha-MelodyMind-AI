import streamlit as st
from pathlib import Path

st.set_page_config(
    page_title="MelodyMind AI",
    page_icon="🎵",
    layout="centered"
)

st.title("🎵 MelodyMind AI")
st.subheader("AI-Powered Music Composer")

st.write("Listen to music generated by our AI music project.")

all_files = [p for p in Path(".").rglob("*") if p.is_file()]

audio_file = next(
    (p for p in all_files if p.suffix.lower() == ".wav"),
    None
)

midi_file = next(
    (p for p in all_files if p.suffix.lower() == ".mid"),
    None
)

st.divider()
st.header("🎧 Generated Music")

if audio_file:
    st.success("Generated music found!")
    st.audio(str(audio_file), format="audio/wav")

    st.download_button(
        "⬇️ Download WAV",
        data=audio_file.read_bytes(),
        file_name="MelodyMind_Generated.wav",
        mime="audio/wav"
    )
else:
    st.error("WAV audio file not found.")

if midi_file:
    st.download_button(
        "⬇️ Download MIDI",
        data=midi_file.read_bytes(),
        file_name="MelodyMind_Generated.mid",
        mime="audio/midi"
    )
else:
    st.warning("MIDI file not found.")

st.divider()
st.caption("Built with Python, TensorFlow and LSTM")
st.info("Model training is still being improved.")
